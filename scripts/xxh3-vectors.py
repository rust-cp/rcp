#!/usr/bin/env python3
"""Writes the XXH3 vector table `tests/xxh3.rs` checks, from the REFERENCE library.

The point is that nothing here is typed by hand. `libxxhash` is the algorithm's own
implementation; this calls it through ctypes and prints what it answered. A table
somebody transcribed from a web page tests the transcription.

    python3 scripts/xxh3-vectors.py > tests/support/xxh3-vectors.txt

Each line is `LENGTH HEX64 HEX128`, over an input of that length filled with a fixed
pattern (byte i = (i * 7 + 3) mod 251, the same one the OCI arms use). The lengths are
every boundary the algorithm's branches have -- 0, 1, 3, 4, 8, 9, 16, 17, 32, 64, 96,
128, 129, 160, 240, 241 -- plus block edges on the long path (1024, 1025, 2048, 4096)
and a few sizes in between, because a hash that is right at the boundaries and wrong in
the middle is a hash that is wrong.

If `libxxhash` is not installed, this exits 2 and says so; the suite skips rather than
inventing a table.
"""

import ctypes
import ctypes.util
import sys

LENGTHS = [
    0, 1, 2, 3, 4, 5, 7, 8, 9, 10, 15, 16, 17, 18, 31, 32, 33, 63, 64, 65, 95, 96, 97,
    127, 128, 129, 130, 159, 160, 191, 192, 239, 240, 241, 242, 255, 256, 257, 511, 512,
    513, 1023, 1024, 1025, 1056, 1088, 2047, 2048, 2049, 3000, 4096, 4097, 10000, 65536,
]


def pattern(n):
    return bytes((i * 7 + 3) % 251 for i in range(n))


def main():
    path = ctypes.util.find_library("xxhash") or "/usr/lib/x86_64-linux-gnu/libxxhash.so.0"
    try:
        lib = ctypes.CDLL(path)
    except OSError as e:
        sys.stderr.write("libxxhash not available (%s): %s\n" % (path, e))
        return 2

    class X128(ctypes.Structure):
        _fields_ = [("low64", ctypes.c_uint64), ("high64", ctypes.c_uint64)]

    lib.XXH3_64bits.restype = ctypes.c_uint64
    lib.XXH3_64bits.argtypes = [ctypes.c_char_p, ctypes.c_size_t]
    lib.XXH3_128bits.restype = X128
    lib.XXH3_128bits.argtypes = [ctypes.c_char_p, ctypes.c_size_t]
    lib.XXH_versionNumber.restype = ctypes.c_uint

    print("# generated by scripts/xxh3-vectors.py from libxxhash %d" % lib.XXH_versionNumber())
    print("# LENGTH HEX64 HEX128, over byte i = (i * 7 + 3) mod 251")
    for n in LENGTHS:
        data = pattern(n)
        h = lib.XXH3_64bits(data, n)
        q = lib.XXH3_128bits(data, n)
        print("%d %016x %016x%016x" % (n, h, q.high64, q.low64))
    return 0


if __name__ == "__main__":
    sys.exit(main())
