//! Keeps `docs/src/reference/cli.md` in step with the tables `rcp describe` publishes.
//!
//! The page is generated from `rcp::describe`, so the reference cannot drift from the
//! parser. When this test fails, regenerate the page and commit it:
//!
//! ```sh
//! UPDATE_DOCS=1 cargo test --test docs
//! ```

use std::fmt::Write as _;
use std::path::Path;

use rcp::describe::{Capability, COMMANDS, EVENTS, EXIT_CODES, OPTIONS, SCHEMES};

const PAGE: &str = "docs/src/reference/cli.md";

/// A table cell: pipes would end the cell and newlines the row.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn yes(flag: bool) -> &'static str {
    if flag {
        "yes"
    } else {
        "no"
    }
}

fn capability(cap: Capability) -> &'static str {
    match cap {
        Capability::Setting => "setting",
        Capability::Runs => "runs a program",
        Capability::Path => "path",
        Capability::Service => "service",
        Capability::Credential => "credential",
        Capability::Transport => "transport",
        Capability::Rail => "safety rail",
    }
}

fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- Generated by tests/docs.rs from src/describe.rs. Do not edit by hand. -->\n\n",
    );
    out.push_str("# Command-line reference\n\n");
    out.push_str("The same tables are available at run time, as JSON, from `rcp describe`.\n\n");

    out.push_str(
        "## Commands\n\n| Command | Arguments | Writes | Summary |\n| --- | --- | --- | --- |\n",
    );
    for c in COMMANDS {
        let takes = if c.takes.is_empty() {
            String::new()
        } else {
            format!("`{}`", cell(c.takes))
        };
        writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            c.name,
            takes,
            yes(c.writes),
            cell(c.summary)
        )
        .unwrap();
    }

    out.push_str("\n## Endpoint schemes\n\n");
    out.push_str("| Scheme | Syntax | Writable | Sparse | Hard links | Symlinks | Xattrs | ACLs | Rename | Identity | Delta | Times | Summary |\n");
    out.push_str(
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for s in SCHEMES {
        writeln!(
            out,
            "| `{}` | `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            s.name,
            cell(s.syntax),
            yes(s.writable),
            yes(s.sparse),
            yes(s.hard_links),
            yes(s.symlinks),
            yes(s.xattrs),
            yes(s.acls),
            yes(s.rename),
            yes(s.identity),
            yes(s.delta),
            cell(s.times),
            cell(s.summary)
        )
        .unwrap();
    }

    out.push_str("\n## Options\n\n| Option | Kind | Summary |\n| --- | --- | --- |\n");
    for (name, cap, summary) in OPTIONS {
        writeln!(
            out,
            "| `-{}` | {} | {} |",
            name,
            capability(*cap),
            cell(summary)
        )
        .unwrap();
    }

    out.push_str("\n## Events\n\nWith `-json`, each line on stdout is one of these events.\n\n| Event | Fields |\n| --- | --- |\n");
    for (event, fields) in EVENTS {
        writeln!(out, "| `{}` | {} |", event, cell(fields)).unwrap();
    }

    out.push_str("\n## Exit codes\n\n| Code | Meaning |\n| --- | --- |\n");
    for (code, meaning) in EXIT_CODES {
        writeln!(out, "| {} | {} |", code, cell(meaning)).unwrap();
    }
    out
}

#[test]
fn cli_reference_is_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(PAGE);
    let want = render();
    if std::env::var_os("UPDATE_DOCS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{PAGE} is out of date; run `UPDATE_DOCS=1 cargo test --test docs` and commit the result"
    );
}
